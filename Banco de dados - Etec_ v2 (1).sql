DROP DATABASE ETEC;

CREATE DATABASE ETEC;

USE ETEC;

-- TABELA ALUNO
CREATE TABLE ALUNO (
    ID_ALUNO INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    NOME VARCHAR(200) NOT NULL,
    DATA_NASCIMENTO DATE NOT NULL,
    CPF CHAR(14) NOT NULL UNIQUE,
    EMAIL VARCHAR(100),
    TELEFONE VARCHAR(20),
    ENDERECO VARCHAR(200),
    MATRICULA VARCHAR(20)
);

-- TABELA PROFESSOR
CREATE TABLE PROFESSOR (
    ID_PROFESSOR INT PRIMARY KEY AUTO_INCREMENT,
    NOME VARCHAR(100) NOT NULL,
    CPF CHAR(14) UNIQUE,
    EMAIL VARCHAR(100),
    TELEFONE VARCHAR(20),
    FORMACAO VARCHAR(100),
    DISCIPLINA_ESPECIALIDADE VARCHAR(100)
);

-- TABELA CURSO
CREATE TABLE CURSO (
    ID_CURSO INT PRIMARY KEY AUTO_INCREMENT,
    NOME VARCHAR(100) NOT NULL,
    MODALIDADE VARCHAR(50),
    CARGA_HORARIA INT
);

-- TABELA TURMA
CREATE TABLE TURMA (
    ID_TURMA INT PRIMARY KEY AUTO_INCREMENT,
    ID_CURSO INT,
    NOME VARCHAR(50) NOT NULL,
    ANO YEAR,
    PERIODO ENUM ('MANHÃ', 'TARDE', 'NOITE'),
    CONSTRAINT FK_TURMA_CURSO FOREIGN KEY (ID_CURSO) REFERENCES CURSO(ID_CURSO)
);

-- TABELA DISCIPLINA
CREATE TABLE DISCIPLINA (
    ID_DISCIPLINA INT PRIMARY KEY AUTO_INCREMENT,
    NOME VARCHAR(100) NOT NULL,
    CARGA_HORARIA INT
);

-- TABELA PROFESSOR_DISCIPLINA_TURMA
CREATE TABLE PROFESSOR_DISCIPLINA_TURMA (
    ID_RELACAO INT PRIMARY KEY AUTO_INCREMENT,
    ID_PROFESSOR INT,
    ID_DISCIPLINA INT,
    ID_TURMA INT,
    CONSTRAINT FK_PDT_PROFESSOR FOREIGN KEY (ID_PROFESSOR) REFERENCES PROFESSOR(ID_PROFESSOR),
    CONSTRAINT FK_PDT_DISCIPLINA FOREIGN KEY (ID_DISCIPLINA) REFERENCES DISCIPLINA(ID_DISCIPLINA),
    CONSTRAINT FK_PDT_TURMA FOREIGN KEY (ID_TURMA) REFERENCES TURMA(ID_TURMA)
);

-- TABELA MATRICULA
CREATE TABLE MATRICULA (
    ID_MATRICULA INT PRIMARY KEY AUTO_INCREMENT,
    ID_ALUNO INT,
    ID_TURMA INT,
    DATA_MATRICULA DATE,
    STATUS ENUM ('ATIVO', 'TRANCADO', 'CONCLUIDO'),
    CONSTRAINT FK_MATRICULA_ALUNO FOREIGN KEY (ID_ALUNO) REFERENCES ALUNO(ID_ALUNO),
    CONSTRAINT FK_MATRICULA_TURMA FOREIGN KEY (ID_TURMA) REFERENCES TURMA(ID_TURMA)
);

-- TABELA NOTAS
CREATE TABLE NOTAS (
    ID_NOTA INT PRIMARY KEY AUTO_INCREMENT,
    ID_ALUNO INT,
    ID_DISCIPLINA INT,
    BIMESTRE TINYINT,
    NOTA DECIMAL(5,2),
    FALTAS INT,
    CONSTRAINT FK_NOTA_ALUNO FOREIGN KEY (ID_ALUNO) REFERENCES ALUNO(ID_ALUNO),
    CONSTRAINT FK_NOTA_DISCIPLINA FOREIGN KEY (ID_DISCIPLINA) REFERENCES DISCIPLINA(ID_DISCIPLINA)
);





